export function findTemplateById(id: string): { template: Template; index: number } | null {
  const cleanId = id.trim().toLowerCase();
  const index = TPLS.findIndex(
    (t) =>
      t.id.toLowerCase() === cleanId ||
      t.n.toLowerCase().replace(/[^a-z0-9]+/g, "-") === cleanId ||
      t.type?.toLowerCase().replace(/[^a-z0-9]+/g, "-") === cleanId,
  );
  if (index !== -1) {
    return { template: TPLS[index], index };
  }
  return null;
}

